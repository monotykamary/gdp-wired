// Writes lean-kernel/library.ts: the Lean twin's sources as strings, so gdp-wired/lean can hand them to a Lean project
// without reading files. `--check` fails if the module is out of date (the suite runs it).
import {readFileSync, writeFileSync} from 'node:fs'
import {join} from 'node:path'

const dir = join(import.meta.dir, '..', 'lean-kernel')
const files = ['Cert.lean', 'Kernel.lean', 'Cyclic.lean', 'Progress.lean', 'StepLaw.lean', 'Steps.lean', 'History.lean', 'Sets.lean', 'Live.lean', 'Ghost.lean', 'Refine.lean', 'Bridge.lean', 'Data.lean']
const text = `// Generated by scripts/gen-lean-library.ts from lean-kernel/*.lean (the twin): do not edit.
export const leanLibrary: Record<string, string> = {
${files.map(f => `  ${JSON.stringify(f)}: ${JSON.stringify(readFileSync(join(dir, f), 'utf8'))},`).join('\n')}
}
`
const out = join(dir, 'library.ts')
if (process.argv.includes('--check')) {
  let current = ''
  try { current = readFileSync(out, 'utf8') } catch { /* missing */ }
  if (current !== text) { console.error('lean-kernel/library.ts is out of date: bun scripts/gen-lean-library.ts'); process.exit(1) }
  console.log('lean-kernel/library.ts is up to date')
} else writeFileSync(out, text)
