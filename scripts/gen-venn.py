# static/venn.svg: the Venn diagram of Lean, Bend and gdp-wired, its labels set in Plus Jakarta Sans (SIL Open Font
# License 1.1), a subset of each weight embedded as woff2 so it renders the same wherever the SVG is shown as an image.
# Every label is measured with the font's own glyph widths and checked to sit inside its region, clear of every circle
# by a margin; a label that touches an edge is printed.
#   curl -fsSL -o PlusJakartaSans.ttf "https://github.com/google/fonts/raw/main/ofl/plusjakartasans/PlusJakartaSans%5Bwght%5D.ttf"
#   python3 scripts/gen-venn.py PlusJakartaSans.ttf static/venn.svg     (needs fonttools and brotli)
import base64, io, math, sys
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools import subset

FONT = sys.argv[1]
OUT = sys.argv[2]

W, H = 920, 744
R = 212
CIRCLES = {
    'lean': (460, 280, '#4f6bed', '#2f49c4', 'Lean'),
    'bend': (338, 480, '#f39237', '#c96a14', 'Bend'),
    'gdp': (582, 480, '#21b884', '#138a60', 'gdp-wired'),
}
# region: (which circles it is inside), center x, first baseline y, lines, size, weight
REGIONS = [
    (('lean',), 460, 146, ['any mathematics', 'proofs you write', 'Mathlib and tactics'], 14, 500),
    (('bend',), 246, 538, ['the proved program,', 'compiled and run', 'on CPUs and GPUs', 'affine resources'], 14, 500),
    (('gdp',), 674, 530, ['no proof to write', 'breaking runs found', 'invariants synthesized', 'liveness, refinement'], 14, 500),
    (('lean', 'bend'), 325, 318, ['dependent types', 'proofs as terms', 'BendTT in Lean'], 13, 500),
    (('lean', 'gdp'), 595, 318, ['every proof a', 'Lean theorem;', 'facts from Lean'], 13, 500),
    (('bend', 'gdp'), 460, 534, ['the GPU:', 'programs, search'], 13, 500),
]
CENTER = (460, 408, ['laws of', 'state machines'], 14, 800)
LINE = 1.36  # line height, in font sizes
MARGIN = 7

def instance(weight):
    f = TTFont(FONT)
    return instancer.instantiateVariableFont(f, {'wght': weight})

texts = ''.join(''.join(r[3]) for r in REGIONS) + ''.join(CENTER[2]) + ''.join(c[4] for c in CIRCLES.values())
fonts = {}
for wt in (500, 800):
    f = instance(wt)
    opts = subset.Options(); opts.flavor = 'woff2'; opts.layout_features = ['kern', 'liga']; opts.name_IDs = ['*']
    sub = subset.Subsetter(opts); sub.populate(text=texts); sub.subset(f)
    buf = io.BytesIO(); f.flavor = 'woff2'; f.save(buf)
    fonts[wt] = (base64.b64encode(buf.getvalue()).decode(), instance(wt))

def width(s, size, wt):
    f = fonts[wt][1]; cmap = f.getBestCmap(); hmtx = f['hmtx']; upem = f['head'].unitsPerEm
    return sum(hmtx[cmap[ord(ch)]][0] for ch in s) * size / upem

def inside(name, x, y, margin):
    cx, cy = CIRCLES[name][:2]
    d = math.hypot(x - cx, y - cy)
    return d <= R - margin

def outside(name, x, y, margin):
    cx, cy = CIRCLES[name][:2]
    return math.hypot(x - cx, y - cy) >= R + margin

def check(regions_in, cx, y0, lines, size, wt):
    bad = []
    for i, s in enumerate(lines):
        w = width(s, size, wt); y = y0 + i * size * LINE
        top, bot = y - 0.74 * size, y + 0.22 * size
        pts = [(x, yy) for x in (cx - w / 2, cx, cx + w / 2) for yy in (top, (top + bot) / 2, bot)]
        for x, yy in pts:
            for n in CIRCLES:
                ok = inside(n, x, yy, MARGIN) if n in regions_in else outside(n, x, yy, MARGIN)
                if not ok:
                    bad.append((s, n, round(x), round(yy)))
    return bad

problems = []
for reg in REGIONS:
    problems += check(*reg)
cx, y0, lines, size, wt = CENTER
problems += check(tuple(CIRCLES), cx, y0, lines, size, wt)
for p in problems:
    print('touches', p)

def text_block(cx, y0, lines, size, wt, fill):
    tsp = ''.join(f'<tspan x="{cx}" dy="{0 if i == 0 else round(size * LINE, 1)}">{s}</tspan>' for i, s in enumerate(lines))
    return f'<text x="{cx}" y="{y0}" font-size="{size}" font-weight="{wt}" fill="{fill}" text-anchor="middle">{tsp}</text>'

out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" role="img" aria-label="What Lean, Bend and gdp-wired each cover, and where they overlap">',
       '<!-- The labels are set in Plus Jakarta Sans (a subset embedded below), Copyright 2020 The Plus Jakarta Sans Project Authors, under the SIL Open Font License 1.1 (https://openfontlicense.org). Generated by scripts/gen-venn.py. -->',
       '<defs>',
       '<style>',
       f'@font-face {{ font-family: "Jakarta"; font-weight: 500; src: url(data:font/woff2;base64,{fonts[500][0]}) format("woff2"); }}',
       f'@font-face {{ font-family: "Jakarta"; font-weight: 800; src: url(data:font/woff2;base64,{fonts[800][0]}) format("woff2"); }}',
       'text { font-family: "Jakarta", "Plus Jakarta Sans", ui-sans-serif, system-ui, -apple-system, "Segoe UI", Helvetica, Arial, sans-serif; letter-spacing: 0.1px; }',
       '</style>',
       '<linearGradient id="bg" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#fdfcfa"/><stop offset="1" stop-color="#f4f1ea"/></linearGradient>',
       '<filter id="soft" x="-20%" y="-20%" width="140%" height="140%"><feDropShadow dx="0" dy="6" stdDeviation="10" flood-color="#1f2328" flood-opacity="0.10"/></filter>',
       '<filter id="pill" x="-30%" y="-60%" width="160%" height="220%"><feDropShadow dx="0" dy="2" stdDeviation="3" flood-color="#1f2328" flood-opacity="0.18"/></filter>']
for name, (cx, cy, col, dark, label) in CIRCLES.items():
    out.append(f'<radialGradient id="g-{name}" cx="0.38" cy="0.32" r="0.8"><stop offset="0" stop-color="{col}" stop-opacity="0.10"/><stop offset="1" stop-color="{col}" stop-opacity="0.26"/></radialGradient>')
out.append('</defs>')
out.append(f'<rect x="1" y="1" width="{W - 2}" height="{H - 2}" rx="28" fill="url(#bg)" stroke="#e4e0d8" stroke-width="1.5"/>')
out.append('<g filter="url(#soft)">')
for name, (cx, cy, col, dark, label) in CIRCLES.items():
    out.append(f'<circle cx="{cx}" cy="{cy}" r="{R}" fill="url(#g-{name})"/>')
out.append('</g>')
for name, (cx, cy, col, dark, label) in CIRCLES.items():
    out.append(f'<circle cx="{cx}" cy="{cy}" r="{R}" fill="none" stroke="{dark}" stroke-width="2.5" stroke-opacity="0.85"/>')
# title pills, outside the circles
pill = {'lean': (460, 34), 'bend': (150, 700), 'gdp': (770, 700)}
for name, (cx, cy, col, dark, label) in CIRCLES.items():
    px, py = pill[name]
    w = width(label, 17, 800) + 34
    out.append(f'<g filter="url(#pill)"><rect x="{px - w / 2:.1f}" y="{py - 17}" width="{w:.1f}" height="34" rx="17" fill="{dark}"/></g>')
    out.append(f'<text x="{px}" y="{py + 6}" font-size="17" font-weight="800" fill="#ffffff" text-anchor="middle">{label}</text>')
for reg in REGIONS:
    out.append(text_block(*reg[1:], '#24292f'))
# the center, on a white pill
cx, y0, lines, size, wt = CENTER
w = max(width(s, size, wt) for s in lines) + 26
h = size * LINE * len(lines) + 14
out.append(f'<g filter="url(#pill)"><rect x="{cx - w / 2:.1f}" y="{y0 - size - 6:.1f}" width="{w:.1f}" height="{h:.1f}" rx="14" fill="#ffffff"/></g>')
out.append(text_block(cx, y0, lines, size, wt, '#1f2328'))
out.append('</svg>')
open(OUT, 'w').write('\n'.join(out) + '\n')
print('wrote', OUT, len('\n'.join(out)) // 1024, 'KB')
