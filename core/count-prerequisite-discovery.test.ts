import {expect,test} from 'bun:test'
import {countPrerequisiteComponents} from './count-prerequisite-components.ts'
test('an unrequired narrow countermodel is parked and remains visible to the core',()=>{
 const q=countPrerequisiteComponents(['extra','core'],new Map(),['core'],[],{discoveryFirst:true,targets:['core']})
 expect(q.next()).toMatchObject({name:'extra',purpose:'discovery',context:['extra']})
 q.finish('extra',{kind:'refuted'})
 expect(q.failed()).toEqual([])
 expect(q.next()).toMatchObject({name:'core',purpose:'required',context:['extra','core']})
 q.finish('core',{kind:'proof',citations:[]});q.commit(['core'])
 expect(q.next()).toBeUndefined();expect(q.unknown()[0]?.reason).toBe('narrow-sat')
})
test('an ordinary target is promoted even when no other law cites it',()=>{
 const q=countPrerequisiteComponents(['target','core'],new Map(),['core'],[],{discoveryFirst:true,targets:['target']})
 q.next();q.finish('target',{kind:'unknown',reason:'budget-expired'})
 expect(q.next()).toMatchObject({name:'core'});q.finish('core',{kind:'proof',citations:[]});q.commit(['core'])
 expect(q.next()).toMatchObject({name:'target',purpose:'required',context:['target','core']})
 q.finish('target',{kind:'proof',citations:[]});q.commit(['target'])
 expect(q.available()).toEqual(['target','core'])
})
test('actual required citations promote a parked dependency, optional offers do not',()=>{
 const recipes=new Map([['core',[{id:'core',kind:'strategy' as const,required:[],optional:['optional']}]]])
 const q=countPrerequisiteComponents(['leaf','optional','core'],new Map(),['core'],[],{discoveryFirst:true,targets:['core'],recipes})
 q.next();q.finish('leaf',{kind:'unknown',reason:'budget-expired'})
 q.next();q.finish('optional',{kind:'unknown',reason:'budget-expired'})
 q.next();q.finish('core',{kind:'proof',citations:['leaf']})
 expect(q.required()).toEqual(['leaf','core'])
 expect(q.next()).toMatchObject({name:'leaf',purpose:'required'})
 q.finish('leaf',{kind:'proof',citations:[]});q.commit(['leaf','core'])
 expect(q.next()).toBeUndefined();expect(q.available()).not.toContain('optional')
})
test('declared required edges promote transitively without promoting optional recipes',()=>{
 const q=countPrerequisiteComponents(['leaf','optional','core'],new Map([['core',['leaf']]]),['core'],[],{discoveryFirst:true,targets:['core']})
 q.next();q.finish('leaf',{kind:'unknown',reason:'budget-expired'})
 q.next();q.finish('optional',{kind:'unknown',reason:'budget-expired'})
 expect(q.required()).toEqual(['leaf','core'])
 expect(q.next()).toMatchObject({name:'leaf',purpose:'required'})
})
test('restored held scopes are never attempted again, including unresolved scopes',()=>{
 const q=countPrerequisiteComponents(['held','dependency','core'],new Map(),['core'],[],{discoveryFirst:true,targets:['held'],held:new Map([['held',['dependency']]]),discovered:['dependency']})
 expect(q.held()).toEqual(['held']);expect(q.available()).toEqual([])
 expect(q.next()).toMatchObject({name:'core'})
 q.finish('core',{kind:'proof',citations:[]});q.commit(['core'])
 expect(q.next()).toMatchObject({name:'dependency',purpose:'required'})
 q.finish('dependency',{kind:'unknown',reason:'budget-expired'})
 expect(q.next()).toBeUndefined();expect(q.held()).toEqual(['held']);expect(q.available()).not.toContain('held')
})
