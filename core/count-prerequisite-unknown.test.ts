import {expect,test} from 'bun:test'
import {countPrerequisiteComponents} from './count-prerequisite-components.ts'
test('unknown required sets do not justify an ordinary dissolution attempt',()=>{
 const q=countPrerequisiteComponents(['a','b'],new Map([['a',['b']],['b',['a']]]),['a','b'])
 expect(q.next()).toMatchObject({name:'a',phase:'joint',recipe:{kind:'strategy'}})
})
test('expired ordinary discovery stays live and joins its actual citer',()=>{
 const q=countPrerequisiteComponents(['leaf','a','b'],new Map([['a',['b']],['b',['a']]]),['a','b'])
 expect(q.next()).toMatchObject({name:'leaf',discovery:true})
 q.finish('leaf',{kind:'unknown',reason:'budget-expired'})
 expect(q.failed()).toEqual([])
 expect(q.next()).toMatchObject({name:'a',component:['a','b'],context:['leaf','a','b']})
 q.finish('a',{kind:'proof',citations:['b','leaf']})
 expect(q.available()).toEqual([])
 expect(q.components()).toContainEqual(['leaf','a','b'])
 expect(q.next()).toMatchObject({name:'leaf',component:['leaf','a','b']})
 q.finish('leaf',{kind:'proof',citations:['a']})
 expect(q.next()).toMatchObject({name:'b'})
 q.finish('b',{kind:'proof',citations:['a']})
 expect(q.next()).toEqual({kind:'ready',members:['leaf','a','b']})
 q.commit(['leaf','a','b']);expect(q.available()).toEqual(['leaf','a','b'])
})
test('a genuinely refuted cited unknown invalidates its actual user',()=>{
 const q=countPrerequisiteComponents(['leaf','a','b'],new Map([['a',['b']],['b',['a']]]),['a','b'])
 q.next();q.finish('leaf',{kind:'unknown',reason:'budget-expired'})
 q.next();q.finish('a',{kind:'proof',citations:['b','leaf']})
 expect(q.next()).toMatchObject({name:'leaf'})
 expect(q.finish('leaf',{kind:'refuted'}).invalidated).toEqual(['a'])
 expect(q.failed()).toEqual(['leaf']);expect(q.retryCount()).toEqual({a:1})
 expect(q.next()).toMatchObject({name:'a',context:['a','b']})
 q.finish('a',{kind:'proof',citations:['b']});q.next();q.finish('b',{kind:'proof',citations:['a']})
 expect(q.next()).toEqual({kind:'ready',members:['a','b']})
})
test('unchanged unknown components park instead of spinning or disappearing',()=>{
 const q=countPrerequisiteComponents(['a','b'],new Map())
 q.next();q.finish('a',{kind:'unknown',reason:'budget-expired'})
 expect(q.next()).toMatchObject({name:'b'})
 q.finish('b',{kind:'unknown',reason:'search'})
 expect(q.next()).toBeUndefined();expect(q.failed()).toEqual([])
 expect(q.unknown().map(value=>value.name)).toEqual(['a','b'])
})
test('an expired required unknown is absorbed by its strategic dependency',()=>{
 const q=countPrerequisiteComponents(['leaf','core'],new Map([['core',['leaf']]]),['core'])
 q.next();q.finish('leaf',{kind:'unknown',reason:'budget-expired'})
 expect(q.components()).toContainEqual(['leaf','core'])
 expect(q.next()).toMatchObject({component:['leaf','core']})
})
test('a ready bottom scope commits before unrelated expensive search',()=>{
 const q=countPrerequisiteComponents(['core','bottom'],new Map([['core',['bottom']]]),['core'])
 expect(q.next()).toMatchObject({name:'bottom'})
 q.finish('bottom',{kind:'proof',citations:[]})
 expect(q.next()).toEqual({kind:'ready',members:['bottom']})
 q.commit(['bottom']);expect(q.next()).toMatchObject({name:'core'})
})
test('a newly committed component reactivates a parked stronger-context query',()=>{
 const q=countPrerequisiteComponents(['a','b'],new Map(),['a','b'])
 expect(q.next()).toMatchObject({name:'a',context:['a']})
 q.finish('a',{kind:'unknown',reason:'search'})
 expect(q.next()).toMatchObject({name:'b',context:['b']})
 q.finish('b',{kind:'proof',citations:[]})
 q.commit(['b'])
 expect(q.next()).toMatchObject({name:'a',context:['a','b']})
 q.finish('a',{kind:'proof',citations:['b']})
 expect(q.next()).toEqual({kind:'ready',members:['a']})
})
test('explicit structural costs select the cheapest unheld member',()=>{
 const q=countPrerequisiteComponents(['expensive','cheap'],new Map([['expensive',['cheap']],['cheap',['expensive']]]),['expensive','cheap'],[],{costs:new Map([['expensive',100],['cheap',1]])})
 expect(q.next()).toMatchObject({name:'cheap',component:['expensive','cheap']})
})
