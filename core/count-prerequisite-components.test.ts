import {expect,test} from 'bun:test'
import {countPrerequisiteComponents} from './count-prerequisite-components.ts'
test('a real induction cycle holds all proofs and admits its conjunction together',()=>{
 const q=countPrerequisiteComponents(['a','b'],new Map([['a',['b']],['b',['a']]]))
 expect(q.next()).toMatchObject({kind:'attempt',name:'a',component:['a','b'],context:['a','b'],phase:'joint'})
 q.finish('a',['b']);expect(q.available()).toEqual([])
 expect(q.next()).toMatchObject({kind:'attempt',name:'b'});q.finish('b',['a'])
 expect(q.next()).toEqual({kind:'ready',members:['a','b']});q.commit(['a','b'])
 expect(q.available()).toEqual(['a','b']);expect(q.next()).toBeUndefined()
})
test('failed dissolution declines nothing and proceeds to a joint attempt',()=>{
 const recipes=new Map([['a',[{id:'strategy',kind:'strategy' as const,required:['b']},{id:'independent',kind:'ordinary' as const,required:[]}]]])
 const q=countPrerequisiteComponents(['a','b'],new Map([['a',['b']],['b',['a']]]),['a'],[],{recipes})
 expect(q.next()).toMatchObject({name:'a',phase:'dissolve',context:['a'],recipe:{id:'independent'}})
 expect(q.finish('a',undefined)).toEqual({held:false,invalidated:[]});expect(q.failed()).toEqual([])
 expect(q.next()).toMatchObject({name:'a',phase:'joint',context:['a','b']})
 q.finish('a',['b']);q.finish((q.next() as {name:string}).name,['a'])
 expect(q.next()).toEqual({kind:'ready',members:['a','b']})
})
test('failure invalidates actual citing proposals and rebuilds them without the failed member',()=>{
 const q=countPrerequisiteComponents(['a','c','b'],new Map([['a',['b']],['b',['c']],['c',['a']]]))
 q.next();q.finish('a',['b']);q.next()
 expect(q.finish('c',undefined)).toEqual({held:false,invalidated:[]})
 expect(q.held()).toEqual(['a']);q.next();q.finish('b',['a'])
 expect(q.held()).toEqual(['a','b']);expect(q.next()).toEqual({kind:'ready',members:['a','b']})
 q.commit(['a','b']);expect(q.failed()).toEqual(['c'])
})
test('a failed actual premise invalidates transitively; survivors are tried again rather than cascaded away',()=>{
 const q=countPrerequisiteComponents(['a','b','c'],new Map([['a',['b']],['b',['c']],['c',['a']]]))
 q.next();q.finish('a',['b']);q.next();q.finish('b',['c']);q.next()
 const result=q.finish('c',undefined)
 expect(new Set(result.invalidated)).toEqual(new Set(['a','b']));expect(q.failed()).toEqual(['c'])
 expect(q.next()).toMatchObject({name:'b'});expect((q.next() as {context:readonly string[]}).context).not.toContain('c');q.finish('b',[])
 expect(q.next()).toEqual({kind:'ready',members:['b']});q.commit(['b'])
 expect(q.next()).toMatchObject({name:'a',context:['a','b','c'].filter(name=>name!=='c')});q.finish('a',['b'])
 expect(q.next()).toEqual({kind:'ready',members:['a']});q.commit(['a'])
 expect(q.available()).toEqual(['a','b']);expect(q.retryCount()).toEqual({a:1,b:1})
})
test('ordinary discovery expands the required graph but does not publish its provisional proof',()=>{
 const q=countPrerequisiteComponents(['caller','helper'],new Map([['helper',['caller']]]))
 expect(q.next()).toMatchObject({name:'caller',discovery:true,context:['caller','helper']})
 q.finish('caller',['helper']);expect(q.available()).toEqual([])
 expect(q.next()).toMatchObject({name:'helper',component:['caller','helper']})
 q.finish('helper',['caller']);expect(q.next()).toEqual({kind:'ready',members:['caller','helper']})
})
test('an undeclared reverse edge merges an incoming dependent, never an unrelated candidate',()=>{
 const recipes=new Map([['unrelated',[{id:'known-independent',kind:'ordinary' as const,required:[]}]]])
 const q=countPrerequisiteComponents(['a','b','later','unrelated'],new Map([['a',['b']],['b',['a']],['later',['a']]]),['a','b','later'],[],{recipes})
 expect(q.next()).toMatchObject({name:'a',phase:'joint',context:['a','b','later']})
 q.finish('a',['b','later'])
 expect(q.components()).toContainEqual(['a','b','later'])
 expect(q.failed()).toEqual([])
 expect(q.next()).toMatchObject({name:'b',component:['a','b','later'],context:['a','b','later']})
 q.finish('b',['a']);q.next();q.finish('later',['a'])
 expect(q.next()).toEqual({kind:'ready',members:['a','b','later']})
})
test('unexpected external or failed citations never enter a held component',()=>{
 const recipes=new Map([['b',[{id:'known-independent',kind:'ordinary' as const,required:[]}]]])
 const q=countPrerequisiteComponents(['a','b'],new Map(),['a'],[],{recipes})
 expect(q.next()).toMatchObject({name:'a',context:['a']})
 q.finish('a',['b']);expect(q.failed()).toEqual(['a']);expect(q.held()).toEqual([])
 expect(q.next()).toMatchObject({name:'b',context:['b']});q.finish('b',['a'])
 expect(q.failed()).toEqual(['a','b']);expect(q.next()).toBeUndefined()
})
test('input renaming and mutation cannot turn a held cyclic proof into admission',()=>{
 const order=['x','y'],edges=['y'],q=countPrerequisiteComponents(order,new Map([['x',edges],['y',['x']]]))
 order.push('intruder');edges.length=0
 expect(q.next()).toMatchObject({component:['x','y']});q.finish('x',['y'])
 expect(()=>q.commit(['x'])).toThrow('component not closed');expect(q.available()).toEqual([])
})
